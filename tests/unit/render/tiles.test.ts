/**
 * THE WRAP SEAM.
 *
 * Reported on the Title screen: the loop was not seamless. It carried a visible
 * jolt, as though the scroll had reached its end and restarted.
 *
 * The cause was not the wrap arithmetic, which was correct - `mod(offsetY, H)`
 * with content drawn at `y` and at `y - H`. It was that the two copies were
 * generated by two passes of a loop that called `rand()` INSIDE it, so the tile
 * at `dy = 0` and the tile at `dy = -h` were different landscapes and a whole
 * new arrangement snapped into frame at the seam. Every generator in the file
 * had the same shape and therefore the same bug.
 *
 * This file is the only thing that stops it coming back. The property is stated
 * once and checked against every generator by table, so a generator added later
 * is checked by the same assertion the day someone adds it to the list - and
 * `wrapY` is the only way to build a wrapping plane, so there is no third path
 * that could quietly re-roll a copy.
 */

const SEED = 0x1a17e;

/** mulberry32, identical to the one `parallax.ts` seeds its content with. */
function rng(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

