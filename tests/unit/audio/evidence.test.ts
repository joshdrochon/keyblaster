describe("audit.md 1.2: no audio item may pass on a graph the game does not play", () => {
  it("every A-21 item is not-implemented when only the graph is evidenced", async () => {
    const results = await runAudioItems({ [ARTIFACT]: evidenceData });
    for (const [id, result] of results) {
      expect(`${id}: ${result.status}`).toBe(`${id}: not-implemented`);
    }
  });

  it("every A-21 item FAILS on a wiring artifact that describes a silent game", async () => {
    // The shape a disconnected build would honestly produce: the graph exists,
    // is correct, runs on the null context nothing in a browser would give it,
    // and has played nothing for anybody.
    const disconnected = connectedWiring();
    disconnected["boot"] = {
      ...(disconnected["boot"] as Record<string, unknown>),
      contextKind: "NullAudioContext",
      framesAfterASecond: 0,
      framesAdvanced: 0,
    };
    disconnected["events"] = Object.fromEntries(
      SFX_EVENTS.map((e) => [e, { count: 0, via: [] }]),
    );
    disconnected["ambient"] = { stops: [], crossfades: 0, crossfadedOnSceneTransition: false };
    disconnected["music"] = { drivenBy: "table", hudSamples: 0, indicesObserved: [0] };
    disconnected["flightCue"] = {
      sfxPlaysBefore: 0,
      sfxPlaysAfter: 0,
      keystrokeCues: 0,
      keystrokePlays: 0,
      scheduled: [],
    };
    disconnected["uiNav"] = { audible: false, masterRmsPeak: 0 };
    disconnected["settings"] = {
      musicGainFollowedSlider: false,
      sfxGainFollowedSlider: false,
      mutedSurvived: true,
    };
    disconnected["duck"] = { measuredOnLiveGraph: false };
    disconnected["coachNote"] = { order: [], textRendered: "", displayFields: [], spoken: [] };

    const results = await runAudioItems({ [ARTIFACT]: evidenceData, [WIRING]: disconnected });
    for (const [id, result] of results) {
      expect(`${id}: ${result.status}`).toBe(`${id}: fail`);
    }
  });

  it("an item cannot pass on a wiring artifact whose plays are only tagged 'test'", async () => {
    // A tag is the provenance of a play. If the only thing that ever reached an
    // event was the harness, the event is not reachable from the game.
    const harnessOnly = connectedWiring();
    harnessOnly["events"] = Object.fromEntries(
      SFX_EVENTS.map((e) => [e, { count: 3, via: ["test:forced"] }]),
    );
    const results = await runAudioItems({ [ARTIFACT]: evidenceData, [WIRING]: harnessOnly });
    expect(results.get("A-21.3")?.status).toBe("fail");
  });
});

