const WIRING = "audio-wiring.json";

/**
 * The real rubric functions, run against a directory of artifacts supplied
 * here. `repo` still points at the real repo so the items' `src/game/audio`
 * existence check is answered honestly; only the evidence is a fixture.
 */
async function runAudioItems(
  artifacts: Record<string, unknown>,
): Promise<Map<string, { status: string; detail: string }>> {
  const port = {
    has: (name: string) => Object.prototype.hasOwnProperty.call(artifacts, name),
    path: (name: string) => `gauntlet/evidence/${name}`,
    read: (name: string) => artifacts[name],
    assertNumber(name: string, key: string, predicate: (v: number) => boolean, what: string) {
      const value = (this.read(name) as Record<string, unknown>)[key];
      if (typeof value !== "number" || Number.isNaN(value)) {
        return { status: "fail", detail: `${name} has no numeric "${key}"` };
      }
      return { status: predicate(value) ? "pass" : "fail", detail: `${what}: ${key} = ${value}` };
    },
    assertShape(name: string, predicate: (d: unknown) => boolean, what: string) {
      return { status: predicate(this.read(name)) ? "pass" : "fail", detail: what };
    },
  };

  const out = new Map<string, { status: string; detail: string }>();
  for (const item of RUBRIC.filter((i) => i.kind === "audio")) {
    out.set(item.id, await item.run({ repo: REPO, evidence: port }));
  }
  return out;
}

